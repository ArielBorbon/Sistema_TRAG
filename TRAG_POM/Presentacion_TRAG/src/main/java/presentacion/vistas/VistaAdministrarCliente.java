    @Override
    public Long obtenerIdClienteSeleccionado() {
        int filaSeleccionada = tblClientes.getSelectedRow();
        if (filaSeleccionada != -1) {
            return (Long) tblClientes.getValueAt(filaSeleccionada, 0);
        }
        return null;
    }

