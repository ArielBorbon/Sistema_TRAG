    private void buscar() {
        limpiarMensajeErrores(); 
        String textoBusqueda = cmpTxtBuscarClientes.getText();
        control.buscarClientes(textoBusqueda);
    }

    @Override
    public void cargarClientes(java.util.List<ClienteResumenDTO> clientes) {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblClientes.getModel();
        modelo.setRowCount(0);

        if (clientes != null) {
            for (ClienteResumenDTO c : clientes) {
                String nombreCompleto = c.getNombre() + " " + c.getApellidoPaterno();

                modelo.addRow(new Object[]{
                    c.getId(),
                    nombreCompleto.trim(),
                    c.getTelefono(),
                    c.getCorreo(),
                    c.getCantidadAutomoviles(),
                    "Eliminar"
                });
            }
        }
    }

